/** Build a menu item object from a data entry */
export const toMenu = (m) => ({
  id: m.id,
  menus_mname: m.name,
  menus_color: m.color,
  menus_micon: resolveMenuIcon(m.icon),
  menus_micon_name: m.icon,
  menus_odrby: m.order,
  menus_mlink: m.link,
  menus_mdesc: m.desc,
});

