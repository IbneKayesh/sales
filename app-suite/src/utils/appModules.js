// Build the flat menus array used for search & recent menus
export const menus = appModules.flatMap((mod) => {
  const items = [];
  if (mod.groups) {
    for (const g of mod.groups) {
      for (const m of g.menus) {
        items.push({
          ...toMenu(m),
          menus_mgrup: g.name,
          menus_mgrup_id: g.id,
          menus_mgrup_order: g.order,
        });
      }
    }
  }
  return items;
});

