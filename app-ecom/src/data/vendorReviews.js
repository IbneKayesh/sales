export const getVendorReviews = (vendorId) => {
  return vendorReviews.filter(r => r.vendorId === vendorId);
};

export const getVendorAverageRating = (vendorId) => {
  const reviews = getVendorReviews(vendorId);
  if (reviews.length === 0) return 0;
  const sum = reviews.reduce((acc, r) => acc + r.rating, 0);
  return Math.round((sum / reviews.length) * 10) / 10;
};

export const getVendorRatingBreakdown = (vendorId) => {
  const reviews = getVendorReviews(vendorId);
  const breakdown = { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 };
  reviews.forEach(r => { breakdown[r.rating]++; });
  return breakdown;
};

